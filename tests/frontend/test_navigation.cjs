const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
function node(id) {return {id,style:{},dataset:{},classList:{add(){},remove(){},toggle(){}},setAttribute(){},removeAttribute(){}};}
const pages = Object.fromEntries(['overview','home','analyze','dashboard','playbook','evidence','iocs','history'].map(id=>[id,node('page-'+id)]));
const tabs = ['uuid','import','url','file','ghidra','demo'].map(id=>node('tab-'+id));
const panes = tabs.map(t=>node(t.id.replace('tab-','pane-')));
let active = 'import';
const location = {pathname:'/analyze/ghidra'};
const stack = [];
const listeners = {};
const network = node('net-ips');network.hidden=false;
const context = {location,history:{pushState(state,unused,path){stack.push(path);location.pathname=path;}},window:{addEventListener(event,cb){listeners[event]=cb;},scrollTo(){}},document:{addEventListener(event,cb){listeners[event]=cb;},getElementById(id){return pages[id.replace('page-','')]||null;},querySelector(){return {id:'tab-'+active};},querySelectorAll(selector){if(selector==='[id^="page-"]')return Object.values(pages);if(selector==='#page-analyze [role="tab"]')return tabs;if(selector==='#page-analyze [role="tabpanel"]')return panes;return [];}}};
vm.createContext(context);
vm.runInContext(fs.readFileSync('static/navigation.js','utf8'),context);
listeners.DOMContentLoaded();
assert.equal(pages.analyze.style.display,'block');
assert.equal(panes.find(p=>p.id==='pane-ghidra').hidden,false);
assert.equal(stack.length,0);
context.showPage('history');
assert.equal(location.pathname,'/history');
context.switchTab('tab-file');
assert.equal(location.pathname,'/analyze/file');
assert.equal(stack.length,2);
location.pathname='/analyze/uuid';listeners.popstate();
assert.equal(panes.find(p=>p.id==='pane-uuid').hidden,false);
assert.equal(stack.length,2);
assert.equal(network.hidden,false);
context.showPage('unknown');assert.equal(stack.length,2);
console.log('Navigation: direct URL, tab URL, Back/Forward restoration, unknown route and network-tab isolation passed.');
